export function parseWord(s) {
  const m = s.match(/뜻\s*:\s*([\s\S]*?)(?:\n\s*문맥\s*:|$)/);
  const c = s.match(/문맥\s*:\s*([\s\S]*)$/);
  return { mean: m ? m[1].trim() : "", ctx: c ? c[1].trim() : "" };
}

